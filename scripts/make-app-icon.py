#!/usr/bin/env python3
"""Generate the application icon from the farm's logo.

    python3 scripts/make-app-icon.py

Writes `public/app-icon-192.png`, `public/app-icon-512.png` and
`public/favicon.svg`, all from the one set of geometry constants below, so
the home-screen icon and the browser tab cannot drift apart.

WHY THE LOGO IS A CORNER BADGE AND NOT THE WHOLE ICON
-----------------------------------------------------
Asked for on 2026-11-03: the farm's mark placed the way Word, Excel and
PowerPoint place their letter — a solid shape to one side of the document
glyph, large enough to be the first thing read, with the glyph still carrying
the shape of the icon. The blue tile and the flask are unchanged; the mark is
added over them at the lower left.

The mark gets a white disc behind it for the same reason the Office letter
tile is a solid colour: the artwork is multicoloured and a red-and-yellow
roundel on a mid-blue field has no edge.

WHY PILLOW AND NOT AN SVG RASTERISER
------------------------------------
There is no rsvg, Inkscape or ImageMagick on the build machine and no
cairosvg in the environment. Pillow is present, so the PNGs are drawn
directly and the SVG is emitted to match. Pillow does not anti-alias
strokes, hence SUPERSAMPLE.
"""
from __future__ import annotations

import base64
import io
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"
SOURCE_LOGO = PUBLIC / "bounty-farm-logo-512.png"

SUPERSAMPLE = 32                 # 64-unit viewBox -> 2048px working canvas
VIEWBOX = 64
BLUE, WHITE, FILL = "#1f63ad", "#ffffff", "#bfdbfe"

CORNER_RADIUS = 12
BADGE_DIAMETER = 26              # ~41% of the icon
BADGE_CENTRE = (17.5, 44.5)      # lower left, overlapping the flask
BADGE_RING = 1.4

# The flask, exactly as the icon has always drawn it.
FLASK_OUTLINE = [
    (26, 12), (38, 12), (38, 25.2), (48.6, 44.6), (48.9, 47.0), (47.8, 50.1),
    (44.2, 52), (19.8, 52), (16.2, 50.1), (15.1, 47.0), (15.4, 44.6),
    (26, 25.2), (26, 12),
]
FLASK_RIM = [(23, 12), (41, 12)]
FLASK_FILL = [
    (20.4, 40), (43.6, 40), (48.2, 48.4), (47.4, 50.6), (45.6, 52),
    (18.4, 52), (16.6, 50.6), (15.8, 48.4),
]
STROKE = 3.5


def render_png(logo: Image.Image) -> Image.Image:
    s = SUPERSAMPLE
    size = VIEWBOX * s

    def u(v: float) -> int:
        return int(round(v * s))

    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, size - 1, size - 1], radius=u(CORNER_RADIUS), fill=BLUE)
    d.polygon([(u(x), u(y)) for x, y in FLASK_FILL], fill=FILL)
    d.line([(u(x), u(y)) for x, y in FLASK_OUTLINE], fill=WHITE, width=u(STROKE), joint="curve")
    d.line([(u(x), u(y)) for x, y in FLASK_RIM], fill=WHITE, width=u(STROKE), joint="curve")

    dia, (cxu, cyu), ring = u(BADGE_DIAMETER), (u(BADGE_CENTRE[0]), u(BADGE_CENTRE[1])), u(BADGE_RING)
    disc = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    ImageDraw.Draw(disc).ellipse(
        [cxu - dia // 2 - ring, cyu - dia // 2 - ring, cxu + dia // 2 + ring, cyu + dia // 2 + ring],
        fill=WHITE,
    )
    img.alpha_composite(disc)

    mark = logo.convert("RGBA").resize((dia, dia), Image.LANCZOS)
    clip = Image.new("L", (dia, dia), 0)
    ImageDraw.Draw(clip).ellipse([0, 0, dia - 1, dia - 1], fill=255)
    mark.putalpha(Image.composite(mark.getchannel("A"), Image.new("L", (dia, dia), 0), clip))
    img.alpha_composite(mark, (cxu - dia // 2, cyu - dia // 2))
    return img


def render_svg(logo: Image.Image) -> str:
    """The same artwork as vector, for the browser tab and the manifest.

    The mark embeds as a 96px raster because it IS a raster — tracing it to
    paths would be redrawing somebody's logo by approximation. 96px is enough
    for a 32px badge at 2x and keeps the file a few kilobytes."""
    small = logo.convert("RGBA").resize((96, 96), Image.LANCZOS)
    buf = io.BytesIO()
    small.save(buf, format="PNG", optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")

    pts = " ".join(f"{x},{y}" for x, y in FLASK_FILL)
    line = " ".join(f"{x},{y}" for x, y in FLASK_OUTLINE)
    cx, cy = BADGE_CENTRE
    r = BADGE_DIAMETER / 2
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VIEWBOX} {VIEWBOX}" role="img" aria-label="BFF Sample Testing">
  <title>BFF Sample Testing</title>
  <!-- GENERATED by scripts/make-app-icon.py. Edit that, not this. -->
  <rect width="{VIEWBOX}" height="{VIEWBOX}" rx="{CORNER_RADIUS}" fill="{BLUE}"/>
  <!-- A sample flask: the one object every one of the logs has in common. -->
  <polygon points="{pts}" fill="{FILL}"/>
  <polyline points="{line}" fill="none" stroke="{WHITE}" stroke-width="{STROKE}" stroke-linejoin="round"/>
  <path d="M23 12h18" fill="none" stroke="{WHITE}" stroke-width="{STROKE}" stroke-linecap="round"/>
  <!-- The farm's mark, where Office puts its letter. The white disc is what
       gives a multicoloured roundel an edge against the blue. -->
  <circle cx="{cx}" cy="{cy}" r="{r + BADGE_RING}" fill="{WHITE}"/>
  <clipPath id="badge"><circle cx="{cx}" cy="{cy}" r="{r}"/></clipPath>
  <image x="{cx - r}" y="{cy - r}" width="{BADGE_DIAMETER}" height="{BADGE_DIAMETER}"
         clip-path="url(#badge)" preserveAspectRatio="xMidYMid slice"
         href="data:image/png;base64,{b64}"/>
</svg>
"""


def main() -> None:
    logo = Image.open(SOURCE_LOGO)
    master = render_png(logo)
    for size in (192, 512):
        master.resize((size, size), Image.LANCZOS).save(PUBLIC / f"app-icon-{size}.png")
        print(f"wrote public/app-icon-{size}.png")
    (PUBLIC / "favicon.svg").write_text(render_svg(logo), encoding="utf-8")
    print("wrote public/favicon.svg")


if __name__ == "__main__":
    main()
